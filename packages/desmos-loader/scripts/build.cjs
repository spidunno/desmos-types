#!/usr/bin/env node
/**
 * Writes dist/index.d.ts and dist/internals.d.ts (after `tsc` has built
 * dist/*.js), replacing the ones `tsc` emits, where `Desmos` is `unknown`.
 *
 * The `Desmos` types come from @spidunno/desmos-types, a dependency, so a
 * newer types release reaches loader users without a new loader release. Its
 * module entry points export the namespace type-only as `Desmos`, and as a
 * value too as `DesmosForLoaders`. This package re-exports the latter as
 * `Desmos`, since its `Desmos` export is a real (live) binding:
 * `Desmos.GraphingCalculator(el)` and `let c: Desmos.GraphingCalculator` both
 * work from one import.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const DIST = path.resolve(__dirname, '..', 'dist');

const declarations = (typesEntry) => `// AUTO-GENERATED by scripts/build.cjs. Do not edit by hand.

import { DesmosForLoaders as Desmos } from '${typesEntry}';
import type { LoadDesmosOptions } from './core.js';
export type { LoadDesmosOptions };
export { DESMOS_VERSION } from './core.js';

/**
 * Fetch calculator.js, run it without creating globals, and return the
 * \`Desmos\` API object. Also sets this package's \`Desmos\` export.
 *
 * Each call loads a separate copy, so call it once and share the result.
 *
 * @example
 * // desmos.ts
 * import { loadDesmos, Desmos } from '@spidunno/desmos-loader';
 * await loadDesmos({ apiKey: 'YOUR_API_KEY' });
 * export { Desmos };
 */
export declare function loadDesmos(options: LoadDesmosOptions): Promise<typeof Desmos>;

/**
 * The Desmos API, once \`loadDesmos\` has resolved (\`undefined\` before that).
 * Usable as a value (\`Desmos.GraphingCalculator(el)\`) and as a namespace of
 * types (\`let calculator: Desmos.GraphingCalculator\`).
 */
export { Desmos };
`;

fs.writeFileSync(path.join(DIST, 'index.d.ts'), declarations('@spidunno/desmos-types/module'));
fs.writeFileSync(path.join(DIST, 'internals.d.ts'), declarations('@spidunno/desmos-types/module/internals'));
console.log('Wrote dist/index.d.ts and dist/internals.d.ts');
