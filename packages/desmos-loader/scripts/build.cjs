#!/usr/bin/env node
/**
 * Writes dist/index.d.ts and dist/internals.d.ts (after `tsc` has built
 * dist/*.js). Each is the matching module-only declaration file from
 * @spidunno/desmos-types plus this package's exports, with `Desmos` exported
 * as a value: this package's `Desmos` export is a real (live) binding, so
 * `Desmos.GraphingCalculator(el)` and `let c: Desmos.GraphingCalculator` both
 * work from one import.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const DIST = path.resolve(__dirname, '..', 'dist');
// The package's `exports` map only lists type entry points, so find it on disk.
const typesRoot = module.paths
  .map((dir) => path.join(dir, '@spidunno', 'desmos-types'))
  .find((dir) => fs.existsSync(path.join(dir, 'package.json')));
if (!typesRoot) throw new Error('@spidunno/desmos-types is not installed');
const typesVersion = JSON.parse(fs.readFileSync(path.join(typesRoot, 'package.json'), 'utf8')).version;

const LOADER_EXPORTS = `
import type { LoadDesmosOptions } from './core.js';
export type { LoadDesmosOptions };
export { DESMOS_VERSION } from './core.js';

/**
 * Fetch calculator.js, run it without creating globals, and return the
 * \`Desmos\` API object. Also sets this package's \`Desmos\` export.
 *
 * Each call loads a separate copy, so call it once and share the result.
 *
 * @example
 * // desmos.ts
 * import { loadDesmos, Desmos } from '@spidunno/desmos-loader';
 * await loadDesmos({ apiKey: 'YOUR_API_KEY' });
 * export { Desmos };
 */
export declare function loadDesmos(options: LoadDesmosOptions): Promise<typeof Desmos>;

/**
 * The Desmos API, once \`loadDesmos\` has resolved (\`undefined\` before that).
 * Usable as a value (\`Desmos.GraphingCalculator(el)\`) and as a namespace of
 * types (\`let calculator: Desmos.GraphingCalculator\`).
 */
export { Desmos };
`;

function build(typesFile, outFile) {
  const source = fs.readFileSync(path.join(typesRoot, 'module', typesFile), 'utf8').replace(/\r\n/g, '\n');
  const typeExport = '\nexport type { Desmos };\n';
  if (!source.includes(typeExport)) throw new Error(`module/${typesFile} no longer ends in \`export type { Desmos }\``);
  // Keep the triple-slash reference first; drop the types package's header comments.
  const body = source.slice(source.indexOf('/// <reference lib="dom" />')).replace(typeExport, '\n');
  const text = [
    `// AUTO-GENERATED by scripts/build.cjs from @spidunno/desmos-types@${typesVersion} module/${typesFile}.`,
    '// Do not edit by hand.',
    body.trimEnd(),
    LOADER_EXPORTS,
  ].join('\n');
  fs.writeFileSync(path.join(DIST, outFile), text);
}

build('index.d.ts', 'index.d.ts');
build('internals.d.ts', 'internals.d.ts');
console.log(`Wrote dist/index.d.ts and dist/internals.d.ts from @spidunno/desmos-types@${typesVersion}`);
