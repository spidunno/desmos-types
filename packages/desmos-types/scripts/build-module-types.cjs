#!/usr/bin/env node
/**
 * Builds the module-only entry points from the global declaration files:
 *
 *   module/index.d.ts      <- index.d.ts
 *   module/internals.d.ts  <- internals/index.d.ts
 *
 * Each output is the referenced files concatenated into one module, so
 * `Desmos` is local to the module instead of a global. The `Window.Desmos`
 * augmentation is dropped.
 *
 * `Desmos` is exported with `export type`: the package has no JavaScript, so
 * a value import would fail at runtime. With a type-only export, using it as
 * a value is a compile error, and auto-imports write `import type`.
 *
 *   node scripts/build-module-types.cjs
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'module');

/** Files referenced by `entry`, depth first, in order, without duplicates. */
function referencedFiles(entry, seen = new Set()) {
  const out = [];
  const text = fs.readFileSync(entry, 'utf8');
  for (const m of text.matchAll(/^\/\/\/ <reference path="([^"]+)" \/>/gm)) {
    const file = path.resolve(path.dirname(entry), m[1]);
    if (seen.has(file)) continue;
    seen.add(file);
    if (path.basename(file) === 'index.d.ts') out.push(...referencedFiles(file, seen));
    else out.push(file);
  }
  return out;
}

function moduleBody(file) {
  return fs
    .readFileSync(file, 'utf8')
    .replace(/\r\n/g, '\n')
    .replace(/^\/\/\/ <reference [^\n]*\n/gm, '')
    // The global `window.Desmos`, which a module version must not declare.
    .replace(/\ninterface Window \{[\s\S]*?\n\}\n/, '\n')
    .trim();
}

function build(entry, outName, description) {
  const files = referencedFiles(path.join(ROOT, entry));
  const parts = files.map((f) => `// ---- ${path.relative(ROOT, f).replace(/\\/g, '/')} ----\n\n${moduleBody(f)}`);
  const text = [
    `// AUTO-GENERATED by scripts/build-module-types.cjs from ${entry}. Do not edit by hand.`,
    `// ${description}`,
    '//',
    '// Unlike the default entry points, this declares no globals: `Desmos` exists',
    '// only where you import it. Use it when the API object is not `window.Desmos`,',
    '// for example when you load calculator.js into a scope of your own:',
    '//',
    "//   import type { Desmos } from '@spidunno/desmos-types/module';",
    '//   declare const api: typeof Desmos;',
    '',
    '/// <reference lib="dom" />',
    '',
    ...parts,
    '',
    'export type { Desmos };',
    '',
  ].join('\n');
  fs.mkdirSync(OUT_DIR, { recursive: true });
  fs.writeFileSync(path.join(OUT_DIR, outName), text);
  return files.length;
}

const pub = build('index.d.ts', 'index.d.ts', 'The public Desmos API v1.13 types, as a module.');
const internals = build('internals/index.d.ts', 'internals.d.ts', 'The public types plus the internals, as a module.');
console.log(`Wrote module/index.d.ts (${pub} files) and module/internals.d.ts (${internals} files)`);
